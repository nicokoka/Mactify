import * as esbuild from "esbuild";

// Bundles src/loader.ts -> dist/customizer/loader.js (IIFE) and, because loader.ts
// imports ./styles.css, esbuild emits dist/customizer/loader.css alongside it.
// The Swift Patcher copies the whole dist/customizer/ folder into xpui.spa.
const options = {
  entryPoints: ["src/loader.ts"],
  bundle: true,
  format: "iife",
  platform: "browser",
  // Spotify's desktop client embeds a recent Chromium; target it generously.
  target: ["chrome120"],
  outfile: "dist/customizer/loader.js",
  sourcemap: false,
  minify: false,
  logLevel: "info",
  banner: {
    js: "/* Spotify Customizer runtime — generated by esbuild. Do not edit. */",
  },
};

if (process.argv.includes("--watch")) {
  const ctx = await esbuild.context(options);
  await ctx.watch();
  console.log("[esbuild] watching…");
} else {
  await esbuild.build(options);
  console.log("[esbuild] built dist/customizer/{loader.js,loader.css}");
}
